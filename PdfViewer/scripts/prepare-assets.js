const fs = require('fs');
const path = require('path');

const rootDir = path.resolve(__dirname, '..');
const workerPath = path.join(rootDir, 'node_modules', 'pdfjs-dist', 'legacy', 'build', 'pdf.worker.min.js');
const cssPath = path.join(rootDir, 'node_modules', 'pdfjs-dist', 'legacy', 'web', 'pdf_viewer.css');
const gifPath = path.join(rootDir, 'node_modules', 'pdfjs-dist', 'legacy', 'web', 'images', 'loading-icon.gif');

const outputTsWorker = path.join(rootDir, 'PdfViewer', 'pdfWorkerBundle.ts');
const outputCssDir = path.join(rootDir, 'PdfViewer', 'css');
const outputCssViewer = path.join(outputCssDir, 'pdf_viewer.css');

if (!fs.existsSync(workerPath)) {
  console.error('[prepare-assets] Worker not found at: ' + workerPath);
  process.exit(1);
}

// 1. Generate TypeScript worker bundle
console.log('[prepare-assets] Reading worker file...');
const workerContent = fs.readFileSync(workerPath, 'utf8');
// Use const with implicit string type to satisfy ESLint no-inferrable-types
const tsWorkerContent = `// Auto-generated by scripts/prepare-assets.js - DO NOT EDIT MANUALLY
export const PDF_WORKER_CODE = ${JSON.stringify(workerContent)};
`;
fs.writeFileSync(outputTsWorker, tsWorkerContent, 'utf8');
console.log(`[prepare-assets] Written ${outputTsWorker} (${(workerContent.length / 1024).toFixed(1)} KB)`);

// 2. Prepare CSS
if (!fs.existsSync(outputCssDir)) {
  fs.mkdirSync(outputCssDir, { recursive: true });
}

let cssContent = fs.readFileSync(cssPath, 'utf8');

// Inline loading-icon.gif as base64 data URI if present
if (fs.existsSync(gifPath)) {
  const gifBase64 = fs.readFileSync(gifPath).toString('base64');
  const gifDataUri = `data:image/gif;base64,${gifBase64}`;
  cssContent = cssContent.replace(/url\(["']?images\/loading-icon\.gif["']?\)/g, `url("${gifDataUri}")`);
}

// Replace non-existent altText svg references with none
cssContent = cssContent.replace(/url\(["']?images\/altText_add\.svg["']?\)/g, 'none');
cssContent = cssContent.replace(/url\(["']?images\/altText_done\.svg["']?\)/g, 'none');

// Verify there are no remaining broken relative url(...) paths
const remainingUrls = cssContent.match(/url\((?!['"]?data:)(?!['"]?#)[^)]+\)/g);
if (remainingUrls) {
  console.warn('[prepare-assets] Warning: Remaining relative URLs in CSS:', remainingUrls);
} else {
  console.log('[prepare-assets] All CSS image URLs successfully sanitized and inlined.');
}

fs.writeFileSync(outputCssViewer, cssContent, 'utf8');
console.log(`[prepare-assets] Written ${outputCssViewer}`);
